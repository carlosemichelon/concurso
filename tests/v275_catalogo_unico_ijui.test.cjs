/* V275 — Biblioteca única, evitando promoção canônica indevida. */
'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const source=p=>fs.readFileSync(path.join(root,p),'utf8');
const json=p=>JSON.parse(source(p));
test('1.554 registros em um único catálogo, preservando IDs e estado editorial',()=>{
 const current=source('index.html'),archived=source('v275.html');
 const meta=json('assets/version.json');
 const base=json('assets/meta_public_v194.json').card_files.flatMap(f=>json('assets/'+f));
 const additions=json('assets/cards_drive_sync_v274.json').new_cards;
 const studies=json('assets/ijui_flashcards_operacionais_v027.json');
 assert.equal(current,archived,'a entrada e o snapshot precisam ser idênticos');
 assert.equal(meta.version,'V275');
 assert.equal(meta.home,'v275.html');
 assert.equal(base.length,1518);
 assert.equal(additions.length,14);
 assert.equal(studies.cards.length,22);
 const all=[...base,...additions,...studies.cards];
 assert.equal(new Set(all.map(c=>c.id)).size,1554);
 assert.equal(all.length,1554);
 assert(!all.some(c=>c.id==='CARD-1499'),'CARD-1499 permanece reservado');
 assert(studies.cards.every(c=>c.canonical===false&&c.id.startsWith('PROP-IJUI-')));
 assert.equal(meta.counts.catalog_entries_unified,1554);
 assert.equal(meta.counts.catalog_canonical_cards,1532);
 assert.equal(meta.counts.catalog_editorial_pending,22);
 assert.match(current,/Biblioteca única de estudo/);
 assert.match(current,/Fichas na biblioteca de estudo/);
 assert.match(current,/const ijui=ij\.cards\.map\(c=>\(\{\.\.\.c,provisional:true,group:'LEGISLACAO',discipline:'Legislação'/);
 assert.match(current,/cards=\[\.\.\.base,\.\.\.ijui\]/);
 assert.match(current,/for\(const c of arr\)\{const k=c\.subject\|\|'Outros';/);
 assert.match(current,/const query=t\.subject;/);
 assert.match(current,/c\.subject\|\|'Outros'\)===\$\('cardTopicFilter'\)\.value/);
 assert.doesNotMatch(current,/c\.provisional\?'Ijuí — legislação FUNDATEC'/);
 assert.doesNotMatch(current,/const query=t\.subject==='Ijuí — legislação FUNDATEC'/);
 assert.match(current,/Seus? dados|SRS privado|SRS permanecem privados|SRS preservado/);
 assert.match(current,/if\(c\.provisional\)/,'a situação editorial precisa ser mostrada no detalhe');
 assert.match(current,/!.*CARD-1430|CARD-1430 a CARD-1451/,'proteger IDs com colisão');
});
