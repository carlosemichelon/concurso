/* V273 — contratos de nomenclatura de versões, contagem e privacidade. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const h=read('index.html'),snapshot=read('v273.html');
const manifest=JSON.parse(read('assets/version.json'));
const inc=JSON.parse(read('assets/estudos_incrementos_v267.json'));
assert.equal(h,snapshot,'index.html deve corresponder à versão publicada');
assert.equal(manifest.version,'V273');
assert.equal(manifest.home,'v273.html');
assert.match(h,/Portal V273 \(interface\)/);
assert.match(h,/Cartões públicos V194/);
assert.match(h,/Adendos V267/);
assert.match(h,/Entenda as versões e os 1\.540 registros/);
assert.match(h,/1\.540 = 1\.518 \+ 22/);
assert.match(h,/19 adendos V267/);
assert.match(h,/Lacunas dos chats/);
assert.match(h,/não são importados automaticamente|não equivale à inclusão/);
assert.doesNotMatch(h,/<footer>Portal V269/);
assert.match(h,/add\.version!=='V267-PETRO17-PETRO20'/,'o carregador precisa manter o contrato corrigido em V272');
assert.equal(inc.version,'V267-PETRO17-PETRO20');
assert.equal(inc.cards.length,19);
assert.equal(manifest.counts.cards_public_base,1518);
assert.equal(manifest.counts.card_operational_ijui,22);
assert.equal(manifest.counts.card_entries_combined,1540);
assert.match(h,/assets\/v271_pdfs_progressive\.js\?v=271-1/,'preservar títulos legíveis de PDFs');
assert.doesNotMatch(h,/1Bq76Tw9o4BPmBSlIj-Dvee3z38Zn4pFA/,'não divulgar ID da fonte privada');
assert.doesNotMatch(h,/1Z3K9QF7l3KG15Ti75bvvzpKgqw1gU2PW/,'não divulgar ID do índice privado');
console.log('V273: semântica de versões, contagem, leitor e privacidade aprovadas');
