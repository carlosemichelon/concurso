const {test,expect}=require('@playwright/test');
const URL='http://127.0.0.1:8765/homologacao-v240/compat-v242.html';
test.setTimeout(120000);
test('V242 compatible staging: one native Controle, one bottom timer, original production untouched',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.stack||e.message));
 await page.goto(URL,{waitUntil:'domcontentloaded',timeout:60000});
 const controlTab=page.locator('#bm240-study-tab');
 await expect(controlTab).toBeAttached({timeout:90000});
 await expect(page.locator('#bm238-study-tab')).toHaveCount(0);
 await expect(page.locator('#bm238-study-frame')).toHaveCount(0);
 const host=page.locator('#bm240-native-host');
 await expect(host.locator('#subjectForm')).toBeAttached({timeout:45000});
 await expect(page.locator('#bm240h-bar')).toBeVisible({timeout:25000});
 await expect(page.locator('#bm240h-bar')).toHaveClass(/bm242-bottom-dock/);
 await expect(page.locator('body > #bm240h-bar')).toHaveCount(1);
 await expect(page.locator('#bm241-bar')).toHaveCount(0);
 await expect(page.locator('html')).toHaveClass(/bm242-dock-enabled/);
 await expect(page.locator('main section#controle-estudos')).toHaveClass(/active/);
 await host.locator('[data-tab="planejamento"]').click();
 await host.locator('#subjectName').fill('Engenharia Civil');
 await host.locator('#subjectForm button[type="submit"]').click();
 await page.locator('#bm240h-subject').selectOption({label:'Engenharia Civil'});
 await page.locator('#bm240h-topic').fill('Fundações');
 await page.locator('#bm240h-start').click();
 await expect(page.locator('#bm240h-bar')).toHaveAttribute('data-state','running');
 await page.waitForTimeout(1400);
 await page.locator('#bm240h-pause').click();
 await expect(page.locator('#bm240h-bar')).toHaveAttribute('data-state','paused');
 await page.locator('#bm240h-save').click();
 await expect(page.locator('#bm240h-bar')).toHaveAttribute('data-state','idle');
 const stored=await page.evaluate(()=>({test:JSON.parse(localStorage.getItem('BM240_HOMOLOGACAO_CONTROLE')),production:localStorage.getItem('BM_CONTROLE_ESTUDOS_V238')}));
 expect(stored.test.sessions).toHaveLength(1);
 expect(stored.test.sessions[0].topic).toBe('Fundações');
 expect(stored.test.sessions[0].minutes).toBeGreaterThan(0);
 expect(stored.production).toBeNull();
 await page.screenshot({path:'test-results/v240-on-v242-desktop.png',fullPage:true});
 expect(errors).toEqual([]);
});
